DROP TABLE IF EXISTS cart_items;
DROP TABLE IF EXISTS order_items;
DROP TABLE IF EXISTS orders;
DROP TABLE IF EXISTS product_images;
DROP TABLE IF EXISTS products;
DROP TABLE IF EXISTS users;
DROP TABLE IF EXISTS categories;

CREATE TABLE users (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name          TEXT NOT NULL CHECK (length(name) BETWEEN 1 AND 60),

  email         TEXT NOT NULL UNIQUE CHECK (email = lower(email)),

  password_hash TEXT NOT NULL,

  role          TEXT NOT NULL DEFAULT 'buyer'
                CHECK (role IN ('buyer', 'seller', 'moderator', 'admin')),

  created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE categories (
  slug     TEXT PRIMARY KEY,
  name     TEXT NOT NULL,
  tagline  TEXT NOT NULL,
  position INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE products (
  id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

  title            TEXT NOT NULL,
  description      TEXT NOT NULL,

  category         TEXT NOT NULL REFERENCES categories (slug),

  price            NUMERIC(10, 2) NOT NULL CHECK (price >= 0),

  compare_at_price NUMERIC(10, 2) CHECK (compare_at_price > price),

  rating           NUMERIC(2, 1) NOT NULL DEFAULT 0 CHECK (rating BETWEEN 0 AND 5),
  review_count     INTEGER NOT NULL DEFAULT 0 CHECK (review_count >= 0),
  stock            INTEGER NOT NULL DEFAULT 0 CHECK (stock >= 0),

  seller_id        INTEGER REFERENCES users (id) ON DELETE SET NULL,

  created_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX products_seller_idx ON products (seller_id);

CREATE INDEX products_category_idx ON products (category);

CREATE TABLE product_images (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

  product_id INTEGER NOT NULL REFERENCES products (id) ON DELETE CASCADE,

  url        TEXT NOT NULL,
  position   INTEGER NOT NULL CHECK (position >= 0),

  UNIQUE (product_id, position)
);

CREATE TABLE cart_items (
  user_id    INTEGER NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  product_id INTEGER NOT NULL REFERENCES products (id) ON DELETE CASCADE,
  quantity   INTEGER NOT NULL CHECK (quantity > 0),
  added_at   TIMESTAMPTZ NOT NULL DEFAULT now(),

  PRIMARY KEY (user_id, product_id)
);

CREATE TABLE orders (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1001) PRIMARY KEY,

  user_id         INTEGER REFERENCES users (id) ON DELETE SET NULL,

  email           TEXT NOT NULL,
  first_name      TEXT NOT NULL,
  last_name       TEXT NOT NULL,
  address         TEXT NOT NULL,
  apartment       TEXT NOT NULL DEFAULT '',
  city            TEXT NOT NULL,
  postal_code     TEXT NOT NULL,
  country         TEXT NOT NULL,
  shipping_method TEXT NOT NULL CHECK (shipping_method IN ('standard', 'express')),

  subtotal        NUMERIC(10, 2) NOT NULL CHECK (subtotal >= 0),
  shipping        NUMERIC(10, 2) NOT NULL CHECK (shipping >= 0),
  tax             NUMERIC(10, 2) NOT NULL CHECK (tax >= 0),
  total           NUMERIC(10, 2) NOT NULL CHECK (total >= 0),

  status          TEXT NOT NULL DEFAULT 'placed'
                  CHECK (status IN ('placed', 'shipped', 'delivered', 'cancelled')),
  created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX orders_user_idx ON orders (user_id);

CREATE TABLE order_items (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id   INTEGER NOT NULL REFERENCES orders (id) ON DELETE CASCADE,

  product_id INTEGER REFERENCES products (id) ON DELETE SET NULL,

  title      TEXT NOT NULL,
  image      TEXT,
  unit_price NUMERIC(10, 2) NOT NULL CHECK (unit_price >= 0),
  quantity   INTEGER NOT NULL CHECK (quantity > 0)
);

CREATE INDEX order_items_order_idx ON order_items (order_id);
