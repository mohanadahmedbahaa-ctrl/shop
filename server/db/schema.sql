-- =====================================================================
-- Oakline database schema (PostgreSQL)
--
-- Run it (from the shop folder):
--   psql -U postgres -d oakline -f server/db/schema.sql
--   psql -U postgres -d oakline -f server/db/seed.sql
--
-- Each TypeScript type in src/data/products.ts becomes a TABLE here:
--   categoryInfo   -> categories
--   Product        -> products
--   images[]       -> product_images (one row per image)
-- =====================================================================

-- 1. START CLEAN. DROP removes the tables so this file can be run again after a change.
--    Order matters: drop the tables that POINT TO others first (images -> products -> users/categories).
--    WARNING: this deletes all data (including user accounts). Fine in development,
--    never run it on a live database.
DROP TABLE IF EXISTS cart_items;
DROP TABLE IF EXISTS order_items;
DROP TABLE IF EXISTS orders;
DROP TABLE IF EXISTS product_images;
DROP TABLE IF EXISTS products;
DROP TABLE IF EXISTS users;
DROP TABLE IF EXISTS categories;


-- 1b. USERS. Everyone who can log in: buyers, sellers, moderators and admins.
CREATE TABLE users (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name          TEXT NOT NULL CHECK (length(name) BETWEEN 1 AND 60),

  -- UNIQUE: two accounts can't share an email. The CHECK forces lowercase, so
  -- "Mo@Mail.com" and "mo@mail.com" can't both exist (the API lowercases before saving).
  email         TEXT NOT NULL UNIQUE CHECK (email = lower(email)),

  -- NEVER store the real password. We store a bcrypt HASH: a one-way scramble.
  -- At login we hash what the user typed and compare. If the database leaks,
  -- attackers get hashes, not passwords.
  password_hash TEXT NOT NULL,

  -- ROLES, from least to most power:
  --   buyer     -> shops (the default)
  --   seller    -> also adds products and deletes their OWN products
  --   moderator -> also deletes ANY product (keeps the catalog clean)
  --   admin     -> everything, plus changing other users' roles
  -- The CHECK works like a TypeScript union type: any other value is rejected.
  role          TEXT NOT NULL DEFAULT 'buyer'
                CHECK (role IN ('buyer', 'seller', 'moderator', 'admin')),

  created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);


-- 2. CATEGORIES. Replaces the `categoryInfo` object.
--    PRIMARY KEY = unique + not null. Every row is identified by its slug ('home', 'kitchen', ...).
--    We use the slug (text) as the key because it's already unique and it's what the URL uses
--    (/shop?category=home), so the API never has to translate ids to slugs.
CREATE TABLE categories (
  slug     TEXT PRIMARY KEY,
  name     TEXT NOT NULL,              -- 'Home & Living'
  tagline  TEXT NOT NULL,
  position INTEGER NOT NULL DEFAULT 0  -- display order in the navbar (SQL tables have NO built-in order)
);


-- 3. PRODUCTS. Replaces the `Product` type.
CREATE TABLE products (
  -- 3a. IDENTITY = the modern version of SERIAL: Postgres picks the next number (1, 2, 3...)
  --     automatically. "BY DEFAULT" still lets the seed insert our existing ids (1-27),
  --     so the URLs /product/3 keep working.
  id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

  title            TEXT NOT NULL,
  description      TEXT NOT NULL,

  -- 3b. FOREIGN KEY: `category` must match a slug that exists in `categories`.
  --     Inserting category 'kitchn' is now an ERROR, like the TypeScript union type, but
  --     enforced by the database for EVERY client (your API, a script, psql...).
  category         TEXT NOT NULL REFERENCES categories (slug),

  -- 3c. MONEY = NUMERIC(10, 2): exact decimals, up to 10 digits with 2 after the point.
  --     Never use REAL/FLOAT for money: they have the same 0.1 + 0.2 problem as JavaScript.
  price            NUMERIC(10, 2) NOT NULL CHECK (price >= 0),

  -- 3d. No NOT NULL = optional (the `?` in compareAtPrice?). NULL means "not on sale".
  --     The CHECK guarantees the old price is really higher, so a "-0%" sale can't exist.
  compare_at_price NUMERIC(10, 2) CHECK (compare_at_price > price),

  -- 3e. CHECK constraints = rules the database refuses to break.
  --     NUMERIC(2, 1) fits 0.0 to 9.9; the CHECK narrows it to a real star rating.
  rating           NUMERIC(2, 1) NOT NULL DEFAULT 0 CHECK (rating BETWEEN 0 AND 5),
  review_count     INTEGER NOT NULL DEFAULT 0 CHECK (review_count >= 0),
  stock            INTEGER NOT NULL DEFAULT 0 CHECK (stock >= 0),

  -- 3f. WHO added the product. NULL = the store's own catalog (the 27 seeded products).
  --     ON DELETE SET NULL: if a seller's account is deleted, their products stay
  --     (owned by the store) instead of the delete being refused.
  seller_id        INTEGER REFERENCES users (id) ON DELETE SET NULL,

  -- 3g. Set automatically on insert. Useful later for "Newest first" sorting.
  --     TIMESTAMPTZ stores the moment in UTC: always prefer it over plain TIMESTAMP.
  created_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Sellers load "my products" (WHERE seller_id = ...), so that foreign key gets an index too.
CREATE INDEX products_seller_idx ON products (seller_id);

-- 4. INDEX. Postgres indexes primary keys automatically, but NOT foreign keys.
--    The shop page filters by category all the time (WHERE category = 'home'),
--    so an index lets Postgres jump to those rows instead of scanning the whole table.
CREATE INDEX products_category_idx ON products (category);


-- 5. PRODUCT IMAGES. Replaces `images: string[]`.
--    Why a separate table instead of a column? One product has MANY images (one-to-many).
--    A table lets the database check each row, and you can add or remove one image
--    without rewriting the others. This is called NORMALIZATION.
CREATE TABLE product_images (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

  -- 5a. ON DELETE CASCADE: when a product is deleted, its images are deleted too.
  --     Without it, Postgres would refuse to delete a product that still has images.
  product_id INTEGER NOT NULL REFERENCES products (id) ON DELETE CASCADE,

  url        TEXT NOT NULL,
  position   INTEGER NOT NULL CHECK (position >= 0),  -- 0 = main image, like images[0]

  -- 5b. A product can't have two images at the same position.
  --     A UNIQUE constraint also creates an index on (product_id, position), so
  --     "all images of product 3" is fast without a separate index.
  UNIQUE (product_id, position)
);


-- 6. CART ITEMS: the cart of a LOGGED-IN user, so it follows them to any device.
--    (Guests keep their cart in the browser's localStorage; it's merged in here at login.)
CREATE TABLE cart_items (
  -- ON DELETE CASCADE on both: deleting a user or a product removes the cart line too.
  user_id    INTEGER NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  product_id INTEGER NOT NULL REFERENCES products (id) ON DELETE CASCADE,
  quantity   INTEGER NOT NULL CHECK (quantity > 0),
  added_at   TIMESTAMPTZ NOT NULL DEFAULT now(),

  -- 6a. COMPOSITE PRIMARY KEY: the PAIR (user, product) is unique. A user can't have two
  --     lines for the same product; adding it again updates the quantity instead
  --     (INSERT ... ON CONFLICT in routes/cart.ts).
  PRIMARY KEY (user_id, product_id)
);


-- 7. ORDERS: one row per checkout.
CREATE TABLE orders (
  -- START WITH 1001: order numbers look like OAK-1001 instead of OAK-1.
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1001) PRIMARY KEY,

  -- SET NULL: if the account is deleted, the order stays in the books (shops must keep them).
  user_id         INTEGER REFERENCES users (id) ON DELETE SET NULL,

  -- 7a. The contact and address are COPIED into the order. If the user later changes their
  --     email, old orders must still show where they were really shipped.
  email           TEXT NOT NULL,
  first_name      TEXT NOT NULL,
  last_name       TEXT NOT NULL,
  address         TEXT NOT NULL,
  apartment       TEXT NOT NULL DEFAULT '',
  city            TEXT NOT NULL,
  postal_code     TEXT NOT NULL,
  country         TEXT NOT NULL,
  shipping_method TEXT NOT NULL CHECK (shipping_method IN ('standard', 'express')),

  -- 7b. Totals are stored as they were AT CHECKOUT (prices and tax rules can change later).
  subtotal        NUMERIC(10, 2) NOT NULL CHECK (subtotal >= 0),
  shipping        NUMERIC(10, 2) NOT NULL CHECK (shipping >= 0),
  tax             NUMERIC(10, 2) NOT NULL CHECK (tax >= 0),
  total           NUMERIC(10, 2) NOT NULL CHECK (total >= 0),

  -- 7c. The order's life cycle. Admins move it forward in the dashboard.
  status          TEXT NOT NULL DEFAULT 'placed'
                  CHECK (status IN ('placed', 'shipped', 'delivered', 'cancelled')),
  created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- "My orders" filters by user all the time.
CREATE INDEX orders_user_idx ON orders (user_id);


-- 8. ORDER ITEMS: the products inside an order (one order has MANY items: one-to-many again).
CREATE TABLE order_items (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id   INTEGER NOT NULL REFERENCES orders (id) ON DELETE CASCADE,

  -- 8a. SET NULL (not CASCADE): deleting a product must NOT delete it from past orders.
  product_id INTEGER REFERENCES products (id) ON DELETE SET NULL,

  -- 8b. A SNAPSHOT of the product at checkout. The receipt must show what the customer
  --     actually paid, even if the seller changes the price or deletes the product tomorrow.
  title      TEXT NOT NULL,
  image      TEXT,
  unit_price NUMERIC(10, 2) NOT NULL CHECK (unit_price >= 0),
  quantity   INTEGER NOT NULL CHECK (quantity > 0)
);

CREATE INDEX order_items_order_idx ON order_items (order_id);
